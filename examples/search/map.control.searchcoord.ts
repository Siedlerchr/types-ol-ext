proj4.defs('ESRI:54009', '+proj=moll +lon_0=0 +x_0=0 +y_0=0 +datum=WGS84 +units=m +no_defs');
register(proj4);
const map = new Map({ target: 'map', view: new View({ zoom: 5, center: [166326, 5992663] }),
  layers: [new TileLayer({ source: new OSM() })] });
const search = new SearchCoordinates();
map.addControl(search);
search.on('select', event => map.getView().animate({ center: event.search.coordinate, zoom: Math.max(map.getView().getZoom() || 0, 5) }));
Object.assign(window, { search });
